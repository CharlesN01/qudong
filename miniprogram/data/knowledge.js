function getSubjects() {
  return subjects.map((subject) => ({
    id: subject.id,
    name: subject.name,
    count: subject.books.reduce((sum, book) => sum + book.points.length, 0)
  }));
}

function getSubject(id) {
  return subjects.find((subject) => subject.id === id) || null;
}

function getBook(subjectId, bookId) {
  const subject = getSubject(subjectId);
  if (!subject) return null;
  return subject.books.find((book) => book.id === bookId) || null;
}

// 搜索：按科目名、书名、知识点题干匹配，返回 { subjectId, bookId, ... }
function search(keyword) {
  const word = String(keyword || '').trim().toLowerCase();
  if (!word) return [];
  const results = [];
  subjects.forEach((subject) => {
    subject.books.forEach((book) => {
      const bookHit = (subject.name + book.name).toLowerCase().includes(word);
      const pointHits = book.points.filter((point) =>
        (point.q + point.a + point.topic).toLowerCase().includes(word)
      );
      if (bookHit || pointHits.length) {
        results.push({
          subjectId: subject.id,
          subjectName: subject.name,
          bookId: book.id,
          bookName: book.name,
          count: pointHits.length || book.points.length
        });
      }
    });
  });
  return results;
}

